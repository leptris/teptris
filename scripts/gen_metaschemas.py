#!/usr/bin/env python3
"""Regenerate src/teptris/schema/metaschemas.c from the official
metaschemas (vendored from the jsonschema crate's metaschemas/
directory). Run with the crate source path as the first argument."""
import json, os, sys

M = sys.argv[1] if len(sys.argv) > 1 else os.path.expanduser(
    '~/.cargo/registry/src/index.crates.io-1949cf8c6b5b557f/'
    'jsonschema-0.60.2/metaschemas')

def load(p):
    with open(p) as f:
        return json.dumps(json.load(f), separators=(',', ':'),
                          ensure_ascii=False)

entries = []
draft7 = load(f'{M}/draft7.json')
entries.append(('http://json-schema.org/draft-07/schema', draft7))
entries.append(('https://json-schema.org/draft-07/schema', draft7))
for draft in ('2019-09', '2020-12'):
    entries.append((f'https://json-schema.org/draft/{draft}/schema',
                    load(f'{M}/draft{draft}/schema.json')))
    metas = ['core', 'applicator', 'validation', 'meta-data', 'content']
    metas += ['format'] if draft == '2019-09' else [
        'unevaluated', 'format-annotation', 'format-assertion']
    for m in metas:
        entries.append((f'https://json-schema.org/draft/{draft}/meta/{m}',
                        load(f'{M}/draft{draft}/meta/{m}.json')))
def c_escape(s):
    out = []
    for ch in s:
        if ch == '"':
            out.append('\\"')
        elif ch == '\\':
            out.append('\\\\')
        elif ord(ch) < 0x20:
            out.append(f'\\x{ord(ch):02x}')
        else:
            out.append(ch)
    return ''.join(out)

lines = ['/* The official JSON Schema metaschemas, vendored as built-in',
         ' * resources: a parser library never touches the network, but the',
         ' * metaschemas are part of the dialect itself. Provenance: the',
         ' * published drafts (draft-07, 2019-09, 2020-12) as shipped by the',
         ' * jsonschema crate v0.60.2 vendored copy; regenerated by',
         ' * scripts/gen_metaschemas.py - edit the script, not this file. */',
         '#include "metaschemas.h"', '',
         'const struct teptris_builtin_resource teptris_builtin_resources[] = {']
for uri, text in entries:
    lines.append(f'    {{"{c_escape(uri)}",')
    esc = c_escape(text)
    i = 0
    while i < len(esc):
        j = min(i + 120, len(esc))
        # never split an escape pair across the chunk edge
        while j > i + 1 and esc[j - 1] == '\\' and esc[j - 2] != '\\':
            j -= 1
        lines.append('        "' + esc[i:j] + '"')
        i = j
    lines.append('    },')
lines.append('};')
lines.append('')
lines.append('const size_t teptris_n_builtin_resources =')
lines.append('    sizeof(teptris_builtin_resources) / sizeof(teptris_builtin_resources[0]);')
with open('src/teptris/schema/metaschemas.c', 'w') as f:
    f.write('\n'.join(lines) + '\n')
print(len(entries), 'resources written')
